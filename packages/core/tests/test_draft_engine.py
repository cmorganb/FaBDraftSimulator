async def test_no_event_payload_references_another_seats_identity(
    fixture_cards: list[Card], fixture_pack_config: PackConfig
) -> None:
    """plan section 6.2 invariant: 'No event ever contains another seat's
    pool.' PACK_PASSED's `from_seat` names a neighboring seat, but only as
    pack-circulation metadata (never that seat's pool/pick) - this is the
    engine's own append-only ground truth, not something handed to an
    agent (that filtering is WP-08's job). Every *other* event type must
    only ever reference `event.seat` itself.
    """
    _, store = await _run(fixture_cards, fixture_pack_config, FirstAvailablePickSource())
    for e in store.events:
        if e.type == "PACK_PASSED":
            continue
        if e.type == "POOL_FINALIZED":
            assert set(e.payload.keys()) == {"total_drafted"}
            continue
        if e.seat is None:
            continue
        # None of these payloads carry a `seat`-shaped field naming a
        # different seat.
        payload_str = json.dumps(e.payload)
        for other_seat in range(8):
            if other_seat == e.seat:
                continue
            assert f'"seat": {other_seat}' not in payload_str


