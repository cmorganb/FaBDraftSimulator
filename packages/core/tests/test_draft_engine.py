async def test_same_seed_and_pick_source_gives_identical_events(
    fixture_cards: list[Card], fixture_pack_config: PackConfig
) -> None:
    source = FirstAvailablePickSource()
    _, store_a = await _run(fixture_cards, fixture_pack_config, source, seed="det")
    _, store_b = await _run(fixture_cards, fixture_pack_config, source, seed="det")

    def strip_wall_time(e: DraftEvent) -> dict[str, Any]:
        d = e.model_dump(mode="json", by_alias=True)
        d.pop("ts_wall")
        return d

    events_a = [strip_wall_time(e) for e in store_a.events]
    events_b = [strip_wall_time(e) for e in store_b.events]
    assert events_a == events_b


async def test_timeout_produces_pick_auto_with_no_response_reason(
    fixture_cards: list[Card], fixture_pack_config: PackConfig
) -> None:
    source = SeatSpecificPickSource(flaky_seat=3, flaky_source=AlwaysTimesOutPickSource())
    state, store = await _run(fixture_cards, fixture_pack_config, source)
    autos = [e for e in store.events if e.type == "PICK_AUTO"]
    assert len(autos) == 14 * 3  # every pick, every round, for seat 3 only
    assert all(e.seat == 3 for e in autos)
    assert all(e.payload["reason"] == "no_response" for e in autos)
    assert all(e.payload["timed_out"] is True for e in autos)
    assert state.timeout_count == 42
    assert len(state.seat_pools[3]) == 42  # still gets a full pool via auto-pick


